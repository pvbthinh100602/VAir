#!/usr/bin/env bash
# VAir Development Environment Setup Script
# Sets up Python virtual environment with ESPHome and development tools
#
# Usage: bash scripts/setup-dev.sh
# Safe to run multiple times (idempotent)

set -euo pipefail

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Repo root (parent of scripts/)
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

echo -e "${BLUE}=== VAir Development Environment Setup ===${NC}"
echo

# Step 1: Detect Python 3.12-3.14
echo -e "${BLUE}[1/5] Checking Python version...${NC}"

PYTHON_CMD=""
PYTHON_VERSION=""

# Try python3.14, python3.13, python3.12, python3, python
for cmd in python3.14 python3.13 python3.12 python3 python; do
    if command -v "$cmd" &> /dev/null; then
        version=$("$cmd" --version 2>&1 | awk '{print $2}')
        major=$(echo "$version" | cut -d. -f1)
        minor=$(echo "$version" | cut -d. -f2)
        
        if [[ "$major" == "3" ]] && [[ "$minor" -ge 12 ]] && [[ "$minor" -le 14 ]]; then
            PYTHON_CMD="$cmd"
            PYTHON_VERSION="$version"
            break
        fi
    fi
done

if [[ -z "$PYTHON_CMD" ]]; then
    echo -e "${RED}ERROR: Python 3.12-3.14 not found.${NC}"
    echo
    echo "ESPHome 2026.10.0 requires Python 3.12, 3.13, or 3.14."
    echo
    echo "Install instructions:"
    echo
    if [[ "$OSTYPE" == "darwin"* ]]; then
        echo "  macOS (using Homebrew):"
        echo "    brew install python@3.13"
        echo "    # or: brew install python@3.12"
    else
        echo "  Ubuntu/Debian:"
        echo "    sudo apt update"
        echo "    sudo apt install python3.13 python3.13-venv"
        echo "    # or: sudo apt install software-properties-common"
        echo "    #      sudo add-apt-repository ppa:deadsnakes/ppa"
        echo "    #      sudo apt install python3.12 python3.12-venv"
        echo
        echo "  Fedora/RHEL:"
        echo "    sudo dnf install python3.13"
    fi
    echo
    echo "Alternative: Use ESPHome 2025.7.5 with Python <3.12"
    echo "  Edit requirements-dev.txt and change esphome version to 2025.7.5"
    exit 1
fi

echo -e "${GREEN}✓ Found Python $PYTHON_VERSION at $(command -v "$PYTHON_CMD")${NC}"
echo

# Step 2: Create virtual environment
echo -e "${BLUE}[2/5] Setting up Python virtual environment...${NC}"

if [[ -d ".venv" ]]; then
    echo -e "${YELLOW}Virtual environment already exists, reusing it.${NC}"
else
    echo "Creating .venv/ ..."
    "$PYTHON_CMD" -m venv .venv
    echo -e "${GREEN}✓ Created .venv/${NC}"
fi
echo

# Step 3: Activate and upgrade pip
echo -e "${BLUE}[3/5] Activating environment and upgrading pip...${NC}"

# Activate venv
source .venv/bin/activate

# Upgrade pip
python -m pip install --upgrade pip --quiet
echo -e "${GREEN}✓ pip upgraded to $(pip --version | awk '{print $2}')${NC}"
echo

# Step 4: Install dependencies
echo -e "${BLUE}[4/5] Installing development dependencies from requirements-dev.txt...${NC}"
echo "This may take a minute..."

pip install -r requirements-dev.txt --quiet

echo -e "${GREEN}✓ Installed:${NC}"
echo "  - esphome $(esphome version 2>/dev/null || echo '(version check failed)')"
echo "  - yamllint $(yamllint --version 2>/dev/null || echo '(version check failed)')"
echo

# Step 5: Create secrets.yaml if it doesn't exist
echo -e "${BLUE}[5/5] Setting up ESPHome secrets file...${NC}"

SECRETS_FILE="firmware/esphome/secrets.yaml"
SECRETS_EXAMPLE="firmware/esphome/secrets.example.yaml"

if [[ -f "$SECRETS_FILE" ]]; then
    echo -e "${YELLOW}$SECRETS_FILE already exists, not overwriting.${NC}"
else
    echo "Creating $SECRETS_FILE from template..."
    
    # Generate a proper base64 32-byte API key
    API_KEY=$(python -c "import secrets, base64; print(base64.b64encode(secrets.token_bytes(32)).decode())")
    
    cat > "$SECRETS_FILE" <<EOF
# ESPHome Secrets Configuration
# AUTO-GENERATED by setup-dev.sh - Edit as needed
# WARNING: This file is gitignored. Never commit secrets!

# WiFi Configuration
wifi_ssid: "YourWiFiSSID"
wifi_password: "YourWiFiPassword"

# Fallback Access Point Password
ap_password: "fallback-ap-password"

# API Encryption Key (auto-generated)
api_encryption_key: "$API_KEY"
EOF
    
    echo -e "${GREEN}✓ Created $SECRETS_FILE with dummy values${NC}"
    echo -e "${YELLOW}  Edit this file with your actual WiFi credentials before flashing!${NC}"
fi
echo

# Success message
echo -e "${GREEN}=== Setup Complete! ===${NC}"
echo
echo "Next steps:"
echo
echo "  1. Activate the environment (required for each new terminal session):"
echo -e "     ${BLUE}source .venv/bin/activate${NC}"
echo
echo "  2. Edit secrets file with your WiFi credentials:"
echo -e "     ${BLUE}nano $SECRETS_FILE${NC}"
echo
echo "  3. Validate the ESPHome configuration:"
echo -e "     ${BLUE}esphome config firmware/esphome/daikin-ftkb35.yaml${NC}"
echo
echo "  4. Run all checks (what CI runs):"
echo -e "     ${BLUE}bash scripts/check.sh${NC}"
echo
echo "  5. When ready to flash hardware, compile the firmware:"
echo -e "     ${BLUE}esphome compile firmware/esphome/daikin-ftkb35.yaml${NC}"
echo
echo "For more details, see: docs/dev-setup.md"
echo
